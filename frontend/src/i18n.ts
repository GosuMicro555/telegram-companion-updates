export type ChannelStatus = "ready" | "joining" | "partial" | "error" | "flood_wait" | "paused";
export type CatalogMembershipCounts = {
  member: number;
  pendingApproval: number;
  joining: number;
  leaving: number;
  failed: number;
};

export function t(locale: Locale, key: MessageKey): string {
  return messages[locale][key];
}

export function tStatus(locale: Locale, status: ChannelStatus): string {
  return messages[locale][status];
}

const catalogStatusKeys = [
  "ready",
  "joining",
  "leaving",
  "removing",
  "partial",
  "error",
  "flood_wait",
  "paused",
  "pending_approval",
  "moderation"
] as const;

export function tCatalogStatus(locale: Locale, status: string): string {
  if ((catalogStatusKeys as readonly string[]).includes(status)) {
    return messages[locale][status as typeof catalogStatusKeys[number]];
  }
  return status || "-";
}

export function formatCatalogMembershipSummary(
  locale: Locale,
  counts: CatalogMembershipCounts
): string {
  const labels = locale === "ru"
    ? {
        member: counts.member === 1 ? "\u0430\u043a\u0442\u0438\u0432\u0435\u043d" : "\u0430\u043a\u0442\u0438\u0432\u043d\u044b",
        pendingApproval: "\u043d\u0430 \u043c\u043e\u0434\u0435\u0440\u0430\u0446\u0438\u0438",
        joining: "\u0432\u0441\u0442\u0443\u043f\u0430\u044e\u0442",
        leaving: "\u0432\u044b\u0445\u043e\u0434\u044f\u0442",
        failed: "\u0441 \u043e\u0448\u0438\u0431\u043a\u043e\u0439"
      }
    : {
        member: "active",
        pendingApproval: "pending approval",
        joining: "joining",
        leaving: "leaving",
        failed: "failed"
      };
  return (Object.keys(labels) as Array<keyof CatalogMembershipCounts>)
    .filter((key) => counts[key] > 0)
    .map((key) => `${counts[key]} ${labels[key]}`)
    .join(" \u00b7 ");
}

type LocaleStorage = Pick<Storage, "getItem" | "setItem">;
const localeStorageKey = "telegram-companion-locale";

export function readStoredLocale(storage: Pick<LocaleStorage, "getItem">): Locale {
  return storage.getItem(localeStorageKey) === "en" ? "en" : "ru";
}

export function persistLocale(storage: Pick<LocaleStorage, "setItem">, locale: Locale): void {
  storage.setItem(localeStorageKey, locale);
}

export function tRuntimeStatus(locale: Locale, status: string): string {
  const normalized = status === "active" || status === "connected" || status === "collecting"
    ? "ready"
    : status === "joining" ? "connecting"
    : status === "partial" ? "backoff"
    : status === "paused" ? "stopped" : status;
  if (normalized === "ready" || normalized === "error" || normalized === "flood_wait" || normalized === "connecting" || normalized === "backoff" || normalized === "stopped") {
    return messages[locale][normalized];
  }
  return status || "-";
}

export function tAccountRuntimeStatus(locale: Locale, status: string, errorCode = ""): string {
  return errorCode === "rpc_auth_key_duplicated"
    ? messages[locale].sessionInvalid
    : tRuntimeStatus(locale, status);
}

export function tAccountRuntimeHint(locale: Locale, errorCode = ""): string {
  return errorCode === "rpc_auth_key_duplicated"
    ? messages[locale].sessionInvalidHint
    : "";
}

export function tBackendStatus(locale: Locale, status: string): string {
	const keys = {
		idle: "statusIdle",
		running: "statusRunning",
		complete: "statusComplete",
		verified: "statusVerified",
		pending: "statusPending",
		queued: "statusQueued",
		cancelling: "statusCancelling",
		error: "error"
	} as const;
	const key = keys[status as keyof typeof keys];
	return key ? messages[locale][key] : status || "-";
}
